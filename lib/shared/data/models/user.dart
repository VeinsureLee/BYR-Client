/// Display name for a post author.
///
/// Anonymous `IWhisper` posts come back with `user_name == null` and an id
/// such as `IWhisper#93`, so fall back to the id instead of showing
/// "未知用户".
String displayUserName(User? user, {String fallback = '未知用户'}) {
  final name = user?.userName;
  if (name != null && name.trim().isNotEmpty) return name;
  final id = user?.id;
  if (id != null && id.trim().isNotEmpty) return id;
  return fallback;
}

/// True for the pseudo-users generated by the anonymous 悄悄话 board.
bool isAnonymousUser(User? user) => (user?.id ?? '').startsWith('IWhisper');

/// User profile. Fields recovered from `remote/model/user.dart`.
class User extends ApiEnvelope {
  final String? id;
  final String? userName;
  final String? faceUrl;
  final int? faceWidth;
  final int? faceHeight;
  final String? gender;
  final String? astro;
  final String? life;
  final String? qq;
  final String? msn;
  final String? homePage;
  final int? level;
  final bool? isOnline;
  final int? postCount;
  final String? lastLoginTime;
  final String? lastLoginIp;
  final bool? isHide;
  final bool? isRegister;
  final int? score;
  final int? followNum;
  final int? fansNum;
  final bool? isFollow;
  final bool? isFan;

  const User({
    super.request,
    super.code,
    super.msg,
    super.error,
    this.id,
    this.userName,
    this.faceUrl,
    this.faceWidth,
    this.faceHeight,
    this.gender,
    this.astro,
    this.life,
    this.qq,
    this.msn,
    this.homePage,
    this.level,
    this.isOnline,
    this.postCount,
    this.lastLoginTime,
    this.lastLoginIp,
    this.isHide,
    this.isRegister,
    this.score,
    this.followNum,
    this.fansNum,
    this.isFollow,
    this.isFan,
  });

  factory User.fromJson(Map<String, dynamic> json) => User(
    request: asString(json['request']),
    code: asString(json['code']),
    msg: asString(json['msg']),
    error: asString(json['error']),
    id: asString(json['id']),
    userName: asString(json['user_name']),
    faceUrl: asString(json['face_url']),
    faceWidth: asInt(json['face_width']),
    faceHeight: asInt(json['face_height']),
    gender: asString(json['gender']),
    astro: asString(json['astro']),
    life: asString(json['life']),
    qq: asString(json['qq']),
    msn: asString(json['msn']),
    homePage: asString(json['home_page']),
    level: asInt(json['level']),
    isOnline: asBool(json['is_online']),
    postCount: asInt(json['post_count']),
    lastLoginTime: asString(json['last_login_time']),
    lastLoginIp: asString(json['last_login_ip']),
    isHide: asBool(json['is_hide']),
    isRegister: asBool(json['is_register']),
    score: asInt(json['score']),
    followNum: asInt(json['follow_num']),
    fansNum: asInt(json['fans_num']),
    isFollow: asBool(json['is_follow']),
    isFan: asBool(json['is_fan']),
  );

  @override
  Map<String, dynamic> toJson() => {
    'request': request,
    'code': code,
    'msg': msg,
    'error': error,
    'id': id,
    'user_name': userName,
    'face_url': faceUrl,
    'face_width': faceWidth,
    'face_height': faceHeight,
    'gender': gender,
    'astro': astro,
    'life': life,
    'qq': qq,
    'msn': msn,
    'home_page': homePage,
    'level': level,
    'is_online': isOnline,
    'post_count': postCount,
    'last_login_time': lastLoginTime,
    'last_login_ip': lastLoginIp,
    'is_hide': isHide,
    'is_register': isRegister,
    'score': score,
    'follow_num': followNum,
    'fans_num': fansNum,
    'is_follow': isFollow,
    'is_fan': isFan,
  };
}
